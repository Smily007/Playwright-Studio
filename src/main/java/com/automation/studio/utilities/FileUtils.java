package com.automation.studio.utilities;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.Comparator;
import java.util.stream.Stream;

public final class FileUtils {
    private static final String GENERATED_MARKER = "Generated by Playwright Test Studio";

    private FileUtils() {}

    public static void ensureDirs(Path... dirs) throws IOException {
        for (Path d : dirs) Files.createDirectories(d);
    }

    public static void write(Path file, String content) throws IOException {
        if (file.getParent() != null) Files.createDirectories(file.getParent());
        Files.writeString(file, content);
    }

    public static void writeGeneratedSource(Path file, String content) throws IOException {
        if (Files.exists(file) && !Files.readString(file).contains(GENERATED_MARKER))
            throw new IOException("Refusing to overwrite a non-generated source file: " + file);
        write(file, content);
    }

    /** Makes a string safe to use as a file or directory name. */
    public static String sanitize(String name) {
        String s = name == null ? "" : name.trim().replaceAll("[^A-Za-z0-9._-]+", "_");
        return s.isEmpty() ? "unnamed" : s;
    }

    public static void copyDir(Path from, Path to) throws IOException {
        try (Stream<Path> s = Files.walk(from)) {
            for (Path p : (Iterable<Path>) s::iterator) {
                Path target = to.resolve(from.relativize(p).toString());
                if (Files.isDirectory(p)) Files.createDirectories(target);
                else {
                    Files.createDirectories(target.getParent());
                    Files.copy(p, target, StandardCopyOption.REPLACE_EXISTING);
                }
            }
        }
    }

    public static void deleteDir(Path dir) throws IOException {
        if (!Files.exists(dir)) return;
        try (Stream<Path> s = Files.walk(dir)) {
            for (Path p : (Iterable<Path>) s.sorted(Comparator.reverseOrder())::iterator) Files.delete(p);
        }
    }
}
