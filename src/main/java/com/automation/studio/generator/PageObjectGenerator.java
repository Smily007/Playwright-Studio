package com.automation.studio.generator;

import com.automation.studio.model.Project;
import com.automation.studio.model.ProjectPageObject;
import com.automation.studio.model.TestCase;
import com.automation.studio.model.TestStep;
import com.automation.studio.utilities.CodeUtil;

import java.net.URI;
import java.util.LinkedHashMap;
import java.util.Map;

/** Builds shared Page Object classes from recorded locators, grouped by application origin. */
public final class PageObjectGenerator {
    public record LocatorReference(String className, String variableName, String methodName) {}

    public record GeneratedPages(Map<String, String> sources,
                                 Map<TestCase, Map<Integer, LocatorReference>> references) {
        public LocatorReference reference(TestCase test, int stepIndex) {
            Map<Integer, LocatorReference> testReferences = references.get(test);
            return testReferences == null ? null : testReferences.get(stepIndex);
        }
    }

    private static final class PageModel {
        private final String className;
        private final String origin;
        private final LinkedHashMap<String, String> methods = new LinkedHashMap<>();

        private PageModel(String className, String origin) {
            this.className = className;
            this.origin = origin;
        }
    }

    public GeneratedPages generate(Project project) {
        Map<String, PageModel> pagesByClass = new LinkedHashMap<>();
        Map<TestCase, Map<Integer, LocatorReference>> references = new LinkedHashMap<>();

        for (TestCase test : project.tests) {
            Map<Integer, LocatorReference> testReferences = new LinkedHashMap<>();
            String currentOrigin = origin(project.baseUrl);
            for (int i = 0; i < test.steps.size(); i++) {
                TestStep step = test.steps.get(i);
                if ("NAVIGATE".equals(step.action)) {
                    String navigatedOrigin = origin(step.param("url"));
                    if (navigatedOrigin != null) currentOrigin = navigatedOrigin;
                }
                if (step.locator == null || currentOrigin == null) continue;

                String className = configuredClass(project, test, currentOrigin);
                if (className == null) className = uniqueClassName(currentOrigin, pagesByClass);
                PageModel page = pagesByClass.get(className);
                if (page != null && !page.origin.equals(currentOrigin))
                    throw new IllegalArgumentException("Page Object class '" + className + "' is assigned to multiple application origins.");
                if (page == null) {
                    page = new PageModel(className, currentOrigin);
                    pagesByClass.put(className, page);
                }
                String expression = step.locator.toJava();
                String method = page.methods.get(expression);
                if (method == null) {
                    method = uniqueMethodName(page, step.locator.summary(), expression);
                    page.methods.put(expression, method);
                }
                testReferences.put(i, new LocatorReference(className, CodeUtil.decap(className), method));
            }
            references.put(test, testReferences);
        }

        Map<String, String> sources = new LinkedHashMap<>();
        for (PageModel page : pagesByClass.values())
            sources.put(page.className, source(page));
        return new GeneratedPages(sources, references);
    }

    private static String configuredClass(Project project, TestCase test, String currentOrigin) {
        if (project.pageObjects == null) return null;
        for (ProjectPageObject pageObject : project.pageObjects) {
            if (pageObject == null || pageObject.className == null || pageObject.testNames == null
                    || !pageObject.testNames.contains(test.name)) continue;
            if (currentOrigin.equals(origin(pageObject.origin))) return pageObject.className;
        }
        return null;
    }

    private static String source(PageModel page) {
        StringBuilder source = new StringBuilder();
        source.append("package pages;\n\n")
                .append("import com.microsoft.playwright.Locator;\n")
                .append("import com.microsoft.playwright.Page;\n")
                .append("import com.microsoft.playwright.options.*;\n")
                .append("import com.automation.studio.runtime.TestData;\n")
                .append("import java.util.Map;\n\n")
                .append("/** Generated by Playwright Test Studio from recorded locators; linked tests share this page object. */\n")
                .append("public final class ").append(page.className).append(" {\n")
                .append("    private final Page page;\n\n")
                .append("    public ").append(page.className).append("(Page page) {\n")
                .append("        this.page = page;\n")
                .append("    }\n");
        for (Map.Entry<String, String> entry : page.methods.entrySet()) {
            source.append("\n    public Locator ").append(entry.getValue()).append("(Map<String, String> vars) {\n")
                    .append("        return ").append(entry.getKey()).append(";\n")
                    .append("    }\n");
        }
        return source.append("}\n").toString();
    }

    private static String methodName(String summary, String expression) {
        String base = CodeUtil.methodName(summary.replaceAll("[^A-Za-z0-9]+", " "));
        if (base.length() > 42) base = base.substring(0, 42);
        return base + "Element" + Integer.toUnsignedString(expression.hashCode(), 36);
    }

    private static String uniqueMethodName(PageModel page, String summary, String expression) {
        String base = methodName(summary, expression);
        String candidate = base;
        int suffix = 2;
        while (page.methods.containsValue(candidate)) candidate = base + suffix++;
        return candidate;
    }

    private static String uniqueClassName(String origin, Map<String, PageModel> pages) {
        URI uri = URI.create(origin);
        String host = uri.getHost() == null ? "Application" : uri.getHost().replace('.', ' ');
        if (uri.getPort() >= 0) host += " Port " + uri.getPort();
        String base = CodeUtil.className(host) + "Page";
        String candidate = base;
        if (pages.containsKey(candidate) && !pages.get(candidate).origin.equals(origin))
            candidate = base + Integer.toUnsignedString(origin.hashCode(), 36);
        return candidate;
    }

    private static String origin(String rawUrl) {
        if (rawUrl == null || rawUrl.isBlank() || rawUrl.contains("${")) return null;
        try {
            URI uri = URI.create(rawUrl);
            if (!uri.isAbsolute() || uri.getHost() == null
                    || !("http".equalsIgnoreCase(uri.getScheme()) || "https".equalsIgnoreCase(uri.getScheme())))
                return null;
            return new URI(uri.getScheme().toLowerCase(), null, uri.getHost().toLowerCase(), uri.getPort(),
                    null, null, null).toString();
        } catch (Exception e) {
            return null;
        }
    }
}
