package com.automation.studio.generator;

import com.automation.studio.actions.ActionCatalog;
import com.automation.studio.actions.ActionDefinition;
import com.automation.studio.actions.StepDescriber;
import com.automation.studio.model.Project;
import com.automation.studio.model.TestCase;
import com.automation.studio.model.TestStep;
import com.automation.studio.utilities.CodeUtil;

/** Generates a compilable TestNG + Playwright Java class; every step is wrapped in StudioBaseTest.step(). */
public class JavaTestGenerator implements CodeGenerator {
    private final ActionCatalog catalog;
    private final PageObjectGenerator pageObjectGenerator = new PageObjectGenerator();

    public JavaTestGenerator(ActionCatalog catalog) { this.catalog = catalog; }

    @Override
    public String className(TestCase test) { return CodeUtil.className(test.name); }

    @Override
    public String generate(TestCase test, Project project) {
        return generate(test, project, pageObjectGenerator.generate(project));
    }

    public String generate(TestCase test, Project project, PageObjectGenerator.GeneratedPages pages) {
        StringBuilder sb = new StringBuilder();
        sb.append("package tests;\n\n");
        boolean usesPageObjects = test.steps.stream().anyMatch(step -> step.locator != null)
                && java.util.stream.IntStream.range(0, test.steps.size()).anyMatch(i -> pages.reference(test, i) != null);
        if (usesPageObjects) sb.append("import pages.*;\n");
        sb.append("import com.microsoft.playwright.*;\n");
        sb.append("import com.microsoft.playwright.options.*;\n");
        sb.append("import com.automation.studio.runtime.*;\n");
        sb.append("import org.testng.Assert;\n");
        sb.append("import org.testng.annotations.Test;\n");
        sb.append("import java.nio.file.*;\n");
        sb.append("import java.util.*;\n");
        sb.append("import static com.microsoft.playwright.assertions.PlaywrightAssertions.assertThat;\n\n");
        sb.append("/** Generated by Playwright Test Studio. Regenerating from recorded steps overwrites manual edits. */\n");
        sb.append("public class ").append(className(test)).append(" extends StudioBaseTest {\n\n");
        sb.append("    @Test(dataProvider = \"studioExcelRows\")\n");
        sb.append("    public void ").append(CodeUtil.methodName(test.name)).append("(Map<String, String> excelRow) {\n");
        sb.append("        vars.putAll(excelRow);\n");
        sb.append("        vars.remove(\"__studio_excel_row\");\n");
        java.util.LinkedHashMap<String, String> pageObjects = new java.util.LinkedHashMap<>();
        for (int i = 0; i < test.steps.size(); i++) {
            PageObjectGenerator.LocatorReference reference = pages.reference(test, i);
            if (reference != null) pageObjects.putIfAbsent(reference.className(), reference.variableName());
        }
        for (var pageObject : pageObjects.entrySet())
            sb.append("        ").append(pageObject.getKey()).append(' ').append(pageObject.getValue())
                    .append(" = new ").append(pageObject.getKey()).append("(page);\n");
        int n = 0;
        boolean soft = false;
        for (int index = 0; index < test.steps.size(); index++) {
            TestStep s = test.steps.get(index);
            n++;
            ActionDefinition d = catalog.get(s.action);
            String desc = StepDescriber.describe(s, d);
            if (!s.enabled) { sb.append("        // [disabled] step ").append(n).append(": ").append(oneLine(desc)).append('\n'); continue; }
            if (d == null) { sb.append("        // [unknown action ").append(s.action).append("] step ").append(n).append('\n'); continue; }
            String body = d.generate(s);
            if (d.id.equals("COMMENT")) { sb.append("        ").append(body).append('\n'); continue; }
            PageObjectGenerator.LocatorReference reference = pages.reference(test, index);
            if (reference != null && s.locator != null)
                body = body.replace(s.locator.toJava(), reference.variableName() + "." + reference.methodName() + "(vars)");
            soft |= s.continueOnFailure;
            sb.append("        step(").append(n).append(", ").append(CodeUtil.literal(desc))
                    .append(s.continueOnFailure ? ", true" : s.breakpoint ? ", false" : "")
                    .append(s.breakpoint ? ", true" : "").append(", () -> {\n");
            for (String line : body.split("\n")) sb.append("            ").append(line).append('\n');
            sb.append("        });\n");
        }
        if (soft) sb.append("        assertNoSoftFailures();\n");
        sb.append("    }\n}\n");
        return sb.toString();
    }

    private static String oneLine(String s) { return s.replace('\n', ' '); }
}
